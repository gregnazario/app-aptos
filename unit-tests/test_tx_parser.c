// Test generic entry function deserialization (unknown function with 2 args: u64 + address)
static void test_generic_entry_function(void **state) {
    (void) state;

    static transaction_t tx;
    // clang-format off
    // Transaction: 0x42::test_mod::do_thing with 2 args (u64=0x0100000000000000, address=0xAA..AA)
    // Layout:
    //   32B prefix + 32B sender + 8B sequence
    //   + payload_variant(ULEB=2) + 32B module_addr + ULEB(8) "test_mod" + ULEB(8) "do_thing"
    //   + ULEB(0) type_args + ULEB(2) num_args
    //   + ULEB(8) + 8B arg1_data + ULEB(32) + 32B arg2_data
    //   + 25B footer
    static const uint8_t raw_tx[] = {
        // PREFIX_RAW_TX_HASHED (32 bytes)
        0xb5, 0xe9, 0x7d, 0xb0, 0x7f, 0xa0, 0xbd, 0x0e,
        0x55, 0x98, 0xaa, 0x36, 0x43, 0xa9, 0xbc, 0x6f,
        0x66, 0x93, 0xbd, 0xdc, 0x1a, 0x9f, 0xec, 0x9e,
        0x67, 0x4a, 0x46, 0x1e, 0xaa, 0x00, 0xb1, 0x93,
        // sender (32 bytes, all 0x11)
        0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11,
        0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11,
        0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11,
        0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11,
        // sequence = 5 (u64 LE)
        0x05, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        // payload_variant = 2 (PAYLOAD_ENTRY_FUNCTION, ULEB128)
        0x02,
        // module_id address (32 bytes, 0x00..42)
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x42,
        // module name len=8 "test_mod"
        0x08, 0x74, 0x65, 0x73, 0x74, 0x5f, 0x6d, 0x6f, 0x64,
        // function name len=8 "do_thing"
        0x08, 0x64, 0x6f, 0x5f, 0x74, 0x68, 0x69, 0x6e, 0x67,
        // type_args count = 0
        0x00,
        // args count = 2
        0x02,
        // arg1: len=8 (u64), value = 1000 (0xE803000000000000 LE)
        0x08, 0xe8, 0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        // arg2: len=32 (address), value = 0xAA..AA
        0x20, 0xaa, 0xaa, 0xaa, 0xaa, 0xaa, 0xaa, 0xaa, 0xaa,
        0xaa, 0xaa, 0xaa, 0xaa, 0xaa, 0xaa, 0xaa, 0xaa,
        0xaa, 0xaa, 0xaa, 0xaa, 0xaa, 0xaa, 0xaa, 0xaa,
        0xaa, 0xaa, 0xaa, 0xaa, 0xaa, 0xaa, 0xaa, 0xaa,
        // Footer (25 bytes):
        // max_gas_amount = 10000 (u64 LE)
        0x10, 0x27, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        // gas_unit_price = 100 (u64 LE)
        0x64, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        // expiration = 1700000000 (u64 LE)
        0x00, 0x28, 0x6b, 0x65, 0x00, 0x00, 0x00, 0x00,
        // chain_id = 1
        0x01
    };
    // clang-format on

    buffer_t buf = {.ptr = raw_tx, .size = sizeof(raw_tx), .offset = 0};
    parser_status_e status = transaction_deserialize(&buf, &tx);

    assert_int_equal(status, PARSING_OK);
    assert_int_equal(tx.tx_variant, TX_RAW);
    assert_int_equal(tx.payload_variant, PAYLOAD_ENTRY_FUNCTION);
    assert_int_equal(tx.payload.entry_function.known_type, FUNC_UNKNOWN);
    assert_int_equal(tx.payload.entry_function.module_id.name.len, 8);
    assert_memory_equal(tx.payload.entry_function.module_id.name.bytes, "test_mod", 8);
    assert_int_equal(tx.payload.entry_function.function_name.len, 8);
    assert_memory_equal(tx.payload.entry_function.function_name.bytes, "do_thing", 8);

    // Check generic args
    assert_int_equal(tx.payload.entry_function.args.generic.num_args, 2);
    assert_int_equal(tx.payload.entry_function.args.generic.num_parsed, 2);
    assert_int_equal(tx.payload.entry_function.args.generic.args[0].type, ARG_TYPE_U64);
    assert_int_equal(tx.payload.entry_function.args.generic.args[0].raw_len, 8);
    assert_int_equal(tx.payload.entry_function.args.generic.args[1].type, ARG_TYPE_ADDRESS);
    assert_int_equal(tx.payload.entry_function.args.generic.args[1].raw_len, 32);

    // Check transaction envelope
    assert_int_equal(tx.sequence, 5);
    assert_int_equal(tx.max_gas_amount, 10000);
    assert_int_equal(tx.gas_unit_price, 100);
    assert_int_equal(tx.chain_id, 1);
}

